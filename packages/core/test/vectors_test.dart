/// UUID (with or without dashes) or plain hex -> bytes.
Uint8List hex(String s) {
  final h = s.replaceAll('-', '');
  return Uint8List.fromList([for (var i = 0; i < h.length; i += 2) int.parse(h.substring(i, i + 2), radix: 16)]);
}

/// Encodes one vector with this package and checks it decodes and verifies.
String encodeVector(Uint8List kE, int eventId, Uint8List ticketId, int zoneId, int? slot) {
  final token = slot == null
      ? encodeStatic(kE, eventId, ticketId, zoneId)
      : encodeRotating(deriveTicketKey(kE, ticketId), eventId, ticketId, zoneId, slot);
  expect(verify(decode(token), eventId: eventId, eventKey: kE, nowSlot: slot ?? 0), isNull);
  return token;
}

Future<void> main() async {
  // Resolved from the package (lib/ -> repo root), not the working directory,
  // so an IDE or another cwd can't silently skip the golden test.
  final lib = await Isolate.resolvePackageUri(Uri.parse('package:jomhor_core/jomhor_core.dart'));
  final goldenFile = File.fromUri(lib!.resolve('../../../docs/token-vectors.json'));

  // INTERIM - replace with the docs/token-vectors.json golden test below when
  // the backend ships it (Lot 1). Expected values come from the independent
  // stdlib-Python implementation in tool/interim_vectors.py, not from this package.
  group('interim known-answer vectors', () {
    final keA = Uint8List.fromList(List.generate(32, (i) => i));
    final keB = Uint8List.fromList(List.filled(32, 0xFF));
    final keC = hex('07fd348a359bcfdb2e69357771fc9a7c78df62ff8b0834e3fcc478688f46c27b');
    const zeros = '00000000-0000-0000-0000-000000000000';
    const ones = 'ffffffff-ffff-ffff-ffff-ffffffffffff';
    const v7 = '0192f0c1-7a3e-7c4d-9b1a-2f3e4d5c6b7a';

    final cases = <(Uint8List, int, String, int, int?, String)>[
      (keA, 1, zeros, 0, null, 'AQAAAAEAAAAAAAAAAAAAAAAAAAAAAADY-OQAv69oEqMuKmsGFGbt'),
      (keB, 0xFFFFFFFF, ones, 0xFFFF, null, 'Af____________________________-pSYKrqUqqRa-brQSqhrNn'),
      (keC, 4242, v7, 12, null, 'AQAAEJIBkvDBej58TZsaLz5NXGt6AAzL3C2r68YM_6EOzHyVF8yf'),
      (keA, 1, zeros, 0, 0, 'AgAAAAEAAAAAAAAAAAAAAAAAAAAAAAAAAAAAwbWQAOILF_FGKbsjCpWAyQ'),
      (keB, 0xFFFFFFFF, ones, 0xFFFF, 0xFFFFFFFF, 'Av__________________________________FrgpyDzZB-IGDRviZ-0Lwg'),
      (keC, 4242, v7, 12, 59000000, 'AgAAEJIBkvDBej58TZsaLz5NXGt6AAwDhETAN2Y8hye_mRwmw86JAJgtcA'),
    ];
    for (final (kE, eventId, ticketId, zoneId, slot, expected) in cases) {
      test('${slot == null ? 'v1' : 'v2'} event $eventId', () {
        expect(encodeVector(kE, eventId, hex(ticketId), zoneId, slot), expected);
      });
    }

    test('K_t', () {
      expect(deriveTicketKey(keC, hex(v7)), hex('ec4cb72d6b3af05e58da412ac6a988cad6433b16870da8f1cf1256fffae15a2a'));
    });
  });

  // Golden test against the backend-generated file (docs/04-api.md §Test vectors):
  // [{k_e, event_id, ticket_id, zone_id, slot?, expected_token}]: k_e 64 lowercase
  // hex, ticket_id canonical lowercase UUID, ints as JSON ints, slot absent for v1.
  test('golden vectors from docs/token-vectors.json', () {
    final vectors = (jsonDecode(goldenFile.readAsStringSync()) as List<dynamic>).cast<Map<String, dynamic>>();
    expect(vectors, isNotEmpty);
    for (final v in vectors) {
      final kE = v['k_e'] as String;
      final ticketId = v['ticket_id'] as String;
      expect(kE, matches(r'^[0-9a-f]{64}$'), reason: 'k_e');
      expect(ticketId, matches(r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'), reason: 'ticket_id');
      final token = encodeVector(hex(kE), v['event_id'] as int, hex(ticketId), v['zone_id'] as int, v['slot'] as int?);
      expect(token, v['expected_token'], reason: 'vector $v');
    }
  }, skip: goldenFile.existsSync() ? false : 'pending: docs/token-vectors.json is generated by the backend in Lot 1');
}

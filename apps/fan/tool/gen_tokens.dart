// Generates lib/theme/tokens.g.dart from design/tokens.json, and the JomhorBrand class
// from design/logo (the app is Jomhor's, ink + amber; a club never re-skins it). Run from apps/fan:
//   dart run tool/gen_tokens.dart
// test/theme_test.dart fails when the committed file is stale.
import 'dart:convert';
import 'dart:io';

const tokensPath = '../../design/tokens.json';
const outputPath = 'lib/theme/tokens.g.dart';
const logoPath = '../../design/logo';

void main() {
  final tokens = jsonDecode(File(tokensPath).readAsStringSync());
  File(outputPath).writeAsStringSync(generateTokens(tokens as Map<String, Object?>));
  stdout.writeln('Wrote $outputPath');
}

String generateTokens(Map<String, Object?> tokens) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from design/tokens.json.')
    ..writeln('// Do not edit: change tokens.json, then run')
    ..writeln('// `dart run tool/gen_tokens.dart` in apps/fan.')
    ..writeln()
    ..writeln("import 'package:flutter/painting.dart';");

  void group(String className, String section, String? Function(String name, Object? value) line) {
    out
      ..writeln()
      ..writeln('abstract final class $className {');
    for (final MapEntry(:key, :value) in (tokens[section]! as Map<String, Object?>).entries) {
      final l = line(key, value);
      if (l != null) out.writeln('  static const $l;');
    }
    out.writeln('}');
  }

  group('JomhorColors', 'color', (name, v) => 'Color $name = ${_color(v! as String)}');
  // The club this build serves (Q23: build-time, one club). `crest` is an asset path, null until there is one.
  group(
    'JomhorClub',
    'club',
    (name, v) => v == null ? 'String? $name = null' : "String $name = '${_escape(v as String)}'",
  );
  group('JomhorFonts', 'font', (name, v) => v is String ? "String $name = '${_escape(v)}'" : null);
  for (final (className, section) in [('JomhorRadius', 'radius'), ('JomhorSpace', 'space'), ('JomhorSize', 'size')]) {
    group(className, section, (name, v) => 'double $name = ${v! as num}');
  }
  group('JomhorMotion', 'motion', (name, v) => '${v is int ? 'int' : 'double'} $name = $v');

  out
    ..writeln()
    ..writeln('/// Family, size, weight, line height and tracking. The fonts are bundled')
    ..writeln('/// (pubspec.yaml `fonts`); `transform` is applied by the widget.')
    ..writeln('abstract final class JomhorType {');
  var first = true;
  for (final MapEntry(:key, :value) in (tokens['type']! as Map<String, Object?>).entries) {
    if (!first) out.writeln();
    first = false;
    final style = value! as Map<String, Object?>;
    final doc = ['${style['font']} face', if (style['transform'] case final String t) t].join(', ');
    final args = [
      'fontFamily: JomhorFonts.${style['font']! as String}',
      // Arabic glyphs (an AR screen, or an Arabic name in any locale) fall back to the face's Arabic family
      // (DESIGN.md Lot 4: Cairo for display, IBM Plex Sans Arabic for body); digits and codes stay Latin.
      'fontFamilyFallback: [JomhorFonts.${style['font'] == 'display' ? 'arabicDisplay' : 'arabicBody'}]',
      'fontSize: ${style['size']! as num}',
      'fontWeight: FontWeight.w${style['weight']! as int}',
      if (style['lineHeight'] case final num h) 'height: $h',
      if (style['letterSpacing'] case final num l) 'letterSpacing: $l',
    ];
    final line = '  static const TextStyle $key = TextStyle(${args.join(', ')});';
    out
      ..writeln('  /// $doc.')
      // Already `dart format`ted (page width 120), so the format check passes on the generated file.
      ..writeln(
        line.length <= 120
            ? line
            : ['  static const TextStyle $key = TextStyle(', for (final a in args) '    $a,', '  );'].join('\n'),
      );
  }
  out.writeln('}');
  _brand(out, tokens['brand']! as Map<String, Object?>);
  return out.toString();
}

/// The Jomhor brand, read from the logo files (design/BRAND.md): fixed, never themed by a club.
void _brand(StringBuffer out, Map<String, Object?> brand) {
  String svg(String name) => File('$logoPath/$name').readAsStringSync();
  final mark = svg('jomhor-mark-transparent.svg');
  final dots = [
    for (final m in RegExp(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)" fill="(#\w{6})"').allMatches(mark))
      (cx: m[1]!, cy: m[2]!, r: m[3]!, fill: m[4]!),
  ];
  final ink = RegExp(r'<rect[^>]*fill="(#\w{6})"').firstMatch(svg('jomhor-mark-dark.svg'))![1]!;
  final wordmark = svg('jomhor-wordmark-dark.svg');
  final wordmarkWidth = RegExp(r'viewBox="0 0 ([\d.]+) 120"').firstMatch(wordmark)![1]!;
  final d = RegExp(' d="([^"]+)"').firstMatch(wordmark)![1]!;
  final lockup = svg('jomhor-lockup-dark.svg');
  final lockupWidth = RegExp(r'viewBox="0 0 ([\d.]+) 120"').firstMatch(lockup)![1]!;
  final markAt = RegExp(r'translate\(0,([\d.]+)\) scale\(([\d.]+)\)').firstMatch(lockup)!;
  final wordmarkX = RegExp(r'translate\(([\d.]+),0\)').firstMatch(lockup)![1]!;
  // Lines of about 100 characters, cut at spaces (each line but the last ends with one).
  final chunks = <String>[];
  for (final word in d.split(' ')) {
    if (chunks.isEmpty || chunks.last.length + word.length > 100) {
      chunks.add('$word ');
    } else {
      chunks.last += '$word ';
    }
  }
  chunks.last = chunks.last.trimRight();
  out
    ..writeln()
    ..writeln('/// The Jomhor brand, from design/logo (design/BRAND.md). Fixed: a club never re-skins it.')
    ..writeln('abstract final class JomhorBrand {')
    ..writeln("  static const String name = '${_escape(brand['name']! as String)}';")
    ..writeln('  static const Color ink = ${_color(ink)};')
    ..writeln('  static const Color white = ${_color(dots.first.fill)};')
    ..writeln('  static const Color amber = ${_color(dots.last.fill)};')
    ..writeln()
    ..writeln(
      '  /// The mark (120 x 120 viewBox, clear space included): (cx, cy, r) of each dot; the last is the twelfth.',
    )
    ..writeln('  static const List<(double, double, double)> dots = [')
    ..writeln([for (final o in dots) '    (${o.cx}, ${o.cy}, ${o.r}),'].join('\n'))
    ..writeln('  ];')
    ..writeln()
    ..writeln('  /// The wordmark outlines (absolute M, L, H, V, C, Z), in a $wordmarkWidth x 120 viewBox.')
    ..writeln('  static const double wordmarkWidth = $wordmarkWidth;')
    ..writeln('  static const String wordmark =')
    ..writeln('${[for (final c in chunks) "      '$c'"].join('\n')};')
    ..writeln()
    ..writeln('  /// The lockup ($lockupWidth x 120): the mark scaled by [lockupMarkScale] and moved down by')
    ..writeln('  /// [lockupMarkDy], the wordmark moved right by [lockupWordmarkX].')
    ..writeln('  static const double lockupWidth = $lockupWidth;')
    ..writeln('  static const double lockupMarkScale = ${markAt[2]};')
    ..writeln('  static const double lockupMarkDy = ${markAt[1]};')
    ..writeln('  static const double lockupWordmarkX = $wordmarkX;')
    ..writeln('}');
}

String _color(String hex) {
  if (!RegExp(r'^#[0-9A-Fa-f]{6}$').hasMatch(hex)) {
    throw FormatException('Expected #RRGGBB', hex);
  }
  return 'Color(0xFF${hex.substring(1).toUpperCase()})';
}

String _escape(String s) => s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$');

// Generates lib/features/checkout/layouts.g.dart from docs/venue-layouts.json (the venue map templates, built in,
// never fetched: docs/04-api.md §Venue map). Run from apps/fan:
//   dart run tool/gen_layouts.dart
// test/layouts_test.dart fails when the committed file is stale.
import 'dart:convert';
import 'dart:io';

const layoutsPath = '../../docs/venue-layouts.json';
const outputPath = 'lib/features/checkout/layouts.g.dart';

void main() {
  final layouts = jsonDecode(File(layoutsPath).readAsStringSync());
  File(outputPath).writeAsStringSync(generateLayouts(layouts as Map<String, Object?>));
  stdout.writeln('Wrote $outputPath');
}

String generateLayouts(Map<String, Object?> json) {
  final canvas = json['canvas']! as Map<String, Object?>;
  String rect(Object? r) => '(${(r! as List<Object?>).map((v) => v! as int).join(', ')})';
  // Already `dart format`ted (page width 120), so the format check passes on the generated file.
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_layouts.dart from docs/venue-layouts.json.')
    ..writeln('// Do not edit: change venue-layouts.json, then run')
    ..writeln('// `dart run tool/gen_layouts.dart` in apps/fan.')
    ..writeln()
    ..writeln('/// `[x, y, w, h]` on the canvas, origin top left.')
    ..writeln('typedef MapRect = (int x, int y, int w, int h);')
    ..writeln()
    ..writeln("/// The decorative centre's `kind`.")
    ..writeln('enum MapCenter { field, stage }')
    ..writeln()
    ..writeln('/// A venue map template: its centre and its slots, in the JSON order (the focus order).')
    ..writeln('class VenueLayout {')
    ..writeln('  const new({required this.center, required this.centerRect, required this.slots});')
    ..writeln()
    ..writeln('  final MapCenter center;')
    ..writeln('  final MapRect centerRect;')
    ..writeln('  final List<(String id, MapRect rect)> slots;')
    ..writeln('}')
    ..writeln()
    ..writeln('abstract final class VenueLayouts {')
    ..writeln('  static const int canvasW = ${canvas['w']! as int};')
    ..writeln('  static const int canvasH = ${canvas['h']! as int};')
    ..writeln()
    ..writeln('  static const Map<String, VenueLayout> all = {');
  for (final MapEntry(:key, :value) in (json['layouts']! as Map<String, Object?>).entries) {
    final layout = value! as Map<String, Object?>;
    final center = layout['center']! as Map<String, Object?>;
    out
      ..writeln("    '$key': VenueLayout(")
      ..writeln('      center: MapCenter.${(center['kind']! as String).toLowerCase()},')
      ..writeln('      centerRect: ${rect(center['rect'])},')
      ..writeln('      slots: [');
    for (final slot in (layout['slots']! as List<Object?>).cast<Map<String, Object?>>()) {
      out.writeln("        ('${slot['id']! as String}', ${rect(slot['rect'])}),");
    }
    out
      ..writeln('      ],')
      ..writeln('    ),');
  }
  out
    ..writeln('  };')
    ..writeln('}');
  return out.toString();
}

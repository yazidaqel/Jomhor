create index on ticket_deliveries (next_attempt_at) where status = 'PENDING';
create index on ticket_deliveries (ticket_id, created_at desc);   -- re-send limit

create type message_channel as enum ('PUSH','WHATSAPP');
create type message_kind    as enum ('TICKET_RECEIVED','SPLIT_INVITE','PAY_CODE','ORDER_PAID','CAMPAIGN');

create table push_tokens (                            -- FCM registration tokens of the Jomhor fan app (one app, every club)
  id            uuid primary key default gen_random_uuid(),   -- platform identity like fan_sessions: no organizer_id;
  user_id       uuid not null references users(id),          -- per-club marketing consent is memberships.marketing_push
  session_id    uuid not null references fan_sessions(id), -- used only while this session is live; deleted when it is revoked
  token         text not null unique,
  platform      text not null check (platform in ('android','ios')),
  updated_at    timestamptz not null default now()
);
create index on push_tokens (user_id);

create type campaign_status   as enum ('DRAFT','SCHEDULED','SENDING','SENT','CANCELLED');
create type campaign_audience as enum ('MEMBERS','EVENT_HOLDERS');

create table campaigns (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  channel       message_channel not null,
  audience      campaign_audience not null,     -- MEMBERS: opted-in members (marketing); EVENT_HOLDERS: VALID holders (service info)
  event_id      integer references events(id),  -- required for EVENT_HOLDERS; the push deep link
  title         text not null,                  -- 1-60 chars, any script
  body          text not null,                  -- 1-500 chars, any script
  status        campaign_status not null default 'DRAFT',
  scheduled_at  timestamptz,
  created_by    uuid not null references staff(id),
  created_at    timestamptz not null default now(),
  started_at    timestamptz,                    -- audience snapshot taken
  finished_at   timestamptz,
  constraint campaigns_event check (audience <> 'EVENT_HOLDERS' or event_id is not null)
);
create index on campaigns (organizer_id, created_at desc);
create index on campaigns (scheduled_at) where status = 'SCHEDULED';

create table fan_messages (                           -- outbox: push and WhatsApp messages other than ticket PDFs (ticket_deliveries)
  id               uuid primary key default gen_random_uuid(),
  organizer_id     uuid not null references organizers(id),
  user_id          uuid not null references users(id),     -- recipient; phone, locale and push tokens read at send time
  channel          message_channel not null,
  kind             message_kind not null,
  campaign_id      uuid references campaigns(id),
  order_id         uuid references orders(id),             -- SPLIT_INVITE, PAY_CODE, ORDER_PAID
  ticket_id        uuid references tickets(id),            -- TICKET_RECEIVED
  status           delivery_status not null default 'PENDING',
  attempts         smallint not null default 0,
  next_attempt_at  timestamptz not null default now(),
  last_error       text,                                   -- provider code or NO_DEVICE / OPTED_OUT / NOT_CONFIGURED; never a phone or body
  created_at       timestamptz not null default now(),
  sent_at          timestamptz,
  constraint fan_messages_campaign check ((kind = 'CAMPAIGN') = (campaign_id is not null))
);
create index on fan_messages (next_attempt_at) where status = 'PENDING';
create unique index on fan_messages (campaign_id, user_id) where campaign_id is not null;          -- one per recipient
create unique index on fan_messages (order_id, kind, channel) where kind in ('SPLIT_INVITE','PAY_CODE','ORDER_PAID');  -- once
create index on fan_messages (user_id, created_at desc) where kind = 'CAMPAIGN' and channel = 'PUSH';  -- inbox

-- ---------- gate ----------
create type device_status as enum ('PENDING','ACTIVE','REVOKED');

create table devices (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  label         text not null,                        -- typed at enrolment ('PDA 12'), 1-40 chars
  public_key    bytea not null unique,                -- ECDSA P-256 SubjectPublicKeyInfo (DER); private key non-exportable in Android Keystore
  status        device_status not null default 'PENDING',
  enrolled_at   timestamptz not null default now(),
  approved_at   timestamptz,
  revoked_at    timestamptz,
  last_seen_at  timestamptz                           -- last request with a valid device signature
);
create index on devices (organizer_id, status);

create table device_assignments (
  organizer_id      uuid not null references organizers(id),
  device_id         uuid not null references devices(id),
  event_id          integer not null references events(id),
  gate_id           uuid not null references gates(id),   -- a gate of the event's venue; the device's starting gate
  manifest_version  integer,                               -- last version this device downloaded (full or delta)
  closed_ack_at     timestamptz,                           -- device confirmed its wipe after close
  primary key (device_id, event_id)
);
create index on device_assignments (event_id);

create table manifests (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  event_id      integer not null references events(id),
  version       integer not null check (version >= 1),
  built_at      timestamptz not null default now(),
  row_count     integer not null,
  signature     bytea not null,                       -- Ed25519 (server gate key) over the uncompressed full payload
  body          bytea not null,                       -- gzip of the full payload text (docs/04-api.md §Manifest payload)
  unique (event_id, version)
);
-- A version is built only when its payload (minus version/since/built_at) differs from the previous one. A delta is the diff of two stored
-- versions, signed when served.

create type scan_direction as enum ('IN','OUT');
create type scan_result as enum ('OK','DUPLICATE','BAD_SIG','BAD_FORMAT','UNKNOWN',
                                 'CANCELLED','BLOCKED','WRONG_ZONE','WRONG_EVENT','EXPIRED_SLOT','OVERRIDE');
create type override_reason as enum ('ID_CHECKED','DEVICE_FAULT','DAMAGED_TICKET','OTHER');

create table scans (
  scan_id         uuid primary key,                   -- UUIDv7 generated on the device
  seq             bigint generated always as identity unique,  -- server arrival order: the used_since cursor
  organizer_id    uuid not null references organizers(id),
  event_id        integer not null references events(id),
  ticket_id       uuid references tickets(id),        -- a ticket of event_id; null when the token was not authenticated
                                                      -- (BAD_FORMAT, WRONG_EVENT, EXPIRED_SLOT, BAD_SIG)
  device_id       uuid not null references devices(id),
  gate_id         uuid not null references gates(id), -- the gate the device was on (a supervisor may move it)
  staff_id        uuid not null references staff(id), -- staff unlocked on the device
  direction       scan_direction not null default 'IN',  -- IN only while re-entry is NONE (plan lot-2 Q33)
  result          scan_result not null,               -- the device's verdict; never updated
  token_version   smallint,
  device_time     timestamptz not null,               -- device clock corrected by the server offset
  received_at     timestamptz not null default now(),
  override_reason override_reason,
  supervisor_id   uuid references staff(id),
  constraint scans_override check ((result = 'OVERRIDE') = (override_reason is not null and supervisor_id is not null))
);
create index on scans (event_id, ticket_id, device_time);   -- canonical admitted scan per ticket
create index on scans (event_id, seq);                      -- used_since
create index on scans (event_id, gate_id, device_time);     -- live dashboard per gate

-- The database refuses any change to scans (V12), even a statement that touches no row.
create function scans_append_only() returns trigger language plpgsql as $$
begin
  raise exception 'scans is append-only: % refused', tg_op using errcode = 'restrict_violation';
end
$$;

create trigger scans_append_only before update or delete or truncate on scans
  for each statement execute function scans_append_only();

-- Append-only: no UPDATE or DELETE on scans, ever. Canonical admitted scan per (ticket_id, direction): the OK or
-- OVERRIDE row with the earliest device_time (tie: lowest scan_id). Later OK/OVERRIDE rows are reported as
-- DUPLICATE_LATE (derived, never stored). Ingestion holds pg_advisory_xact_lock per event, so seq commits in
-- order and a cursor never skips a row.


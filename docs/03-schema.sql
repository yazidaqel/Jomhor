create extension if not exists pgcrypto;

-- Tenant rule: every table carries organizer_id, except platform identity tables
-- organizers, users, otp_challenges, fan_sessions, push_tokens (one fan account and one fan app across organizers).
-- audit_log.organizer_id is nullable for SYSTEM actions.
-- Every query on a tenant table filters by organizer_id (no composite FKs: app scoping
-- is needed anyway to return 404 on foreign ids; tested per endpoint).

-- ---------- tenancy ----------
create type organizer_kind as enum ('SPORTS_CLUB','PROMOTER','VENUE','OTHER');

create table organizers (
  id            uuid primary key default gen_random_uuid(),
  name          text not null,
  kind          organizer_kind not null default 'OTHER',
  settings      jsonb not null default '{}'::jsonb,
  created_at    timestamptz not null default now(),
  slug          text unique                           -- public handle (jomhor.ma/{slug}); null = unlisted: not in /fan/organizers nor in "Tout"
                constraint organizers_slug check (
                  slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(slug) between 2 and 40
                  and slug not in ('all', 'api', 'apple-icon', 'ar', 'club', 'clubs', 'en', 'events', 'favicon', 'fr',
                                   'help', 'icon', 'legal', 'login', 'logout', 'manifest', 'me', 'mine',
                                   'opengraph-image', 'orders', 'robots', 'sitemap', 'twitter-image'))
                                                    -- reserved: web shop top-level paths, ?club= values, locale prefixes
);
-- organizers.settings shape: {"crest_url": "https://assets.jomhor.ma/crests/atlas-fc.svg"}
--   the club crest: content only (design/BRAND.md, not white-label). Returned to fans only under the configured crest
--   base URL (docs/04-api.md §Club directory), else null. Set by ops until a back-office editor exists.
--   A Lot 0 "theme" object, if present, is never read by the fan app, the web shop or the scanner.
--   "cash_points": [{"name": "Guichet Stade de l'Atlas", "address": "Porte 1", "hours": "Lun–Sam 10:00–19:00"}]
--   where fans pay a cash code in person; shown on the cash order page. Set by ops until a back-office editor exists.
--   "loyalty": {"tiers": [{"code": "T1", "name": {"fr": "Membre", "ar": "منخرط", "en": "Member"}, "min_events": 0},
--                         {"code": "T2", "name": {"fr": "Fidèle", "ar": "وفي", "en": "Regular"}, "min_events": 3},
--                         {"code": "T3", "name": {"fr": "Pilier", "ar": "ركيزة", "en": "Stalwart"}, "min_events": 10}]}
--   tiers by min_events ascending, the first at 0; absent or malformed = these defaults; a missing locale falls back to "fr".

create table users (
  id            uuid primary key default gen_random_uuid(),
  phone_e164    text not null unique,
  display_name  text,
  locale        text not null default 'fr',
  created_at    timestamptz not null default now()
);

create type staff_role as enum ('ADMIN','OPS','GATE','SUPERVISOR','FINANCE','CASHIER');
-- CASHIER: back-office OTP login (staff.user_id set), point of sale only (docs/04-api.md §Point of sale). No PIN.

create table staff (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  user_id       uuid references users(id),            -- back-office staff log in by phone OTP; null = PIN-only gate staff
  name          text not null,
  role          staff_role not null,
  pin_hash      text,   -- scanner PIN verifier 'pbkdf2-sha256$10000$<salt>$<hash>' (docs/04-api.md §Gate PINs).
                        -- GATE/SUPERVISOR rows only; the 4-digit PIN is generated by the server and shown once.
                        -- Shipped to the organizer's scanners: a UI lock, brute-forceable offline by design.
  active        boolean not null default true,
  created_at    timestamptz not null default now(),
  unique (organizer_id, user_id)
);

create table otp_challenges (
  id            uuid primary key default gen_random_uuid(),
  phone_e164    text not null,
  audience      text not null default 'fan' check (audience in ('fan','org')),  -- a code verifies only on its own audience
  ip            inet,                                 -- requester (trusted-proxy resolved), for the per-IP throttle
  code_hash     text not null,                        -- HMAC-SHA256(server secret, code); the code is never stored
  attempts      smallint not null default 0 check (attempts <= 5),
  expires_at    timestamptz not null,                 -- created_at + 5 min
  consumed_at   timestamptz,
  created_at    timestamptz not null default now()
);
create index on otp_challenges (phone_e164, audience, created_at desc);
  -- per phone+audience: 3 sends / 10 min, 10 sends / 24 h; sum(attempts) of failed codes >= 15 in 24 h -> locked
create index on otp_challenges (ip, created_at desc);   -- per IP: docs/04-api.md §Fan auth

create table fan_sessions (
  id            uuid primary key default gen_random_uuid(),   -- JWT `sid`
  user_id       uuid not null references users(id),
  created_at    timestamptz not null default now(),
  expires_at    timestamptz not null,                 -- = JWT exp (30 d)
  revoked_at    timestamptz
);
create index on fan_sessions (user_id) where revoked_at is null;


-- ---------- catalog ----------
create table venues (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  name          text not null,
  city          text,
  capacity      integer not null check (capacity > 0),
  timezone      text not null default 'Africa/Casablanca'  -- IANA zone; every wall time for this venue's events
);

create table zones (
  id            smallserial primary key,              -- 2-byte zone_id in the QR; global sequence, ceiling 32,767 zones platform-wide
  organizer_id  uuid not null references organizers(id),
  venue_id      uuid not null references venues(id),
  code          text not null,                        -- 'NORD', 'EST'
  name          text not null,
  capacity      integer not null check (capacity >= 0),
  seated        boolean not null default false,
  unique (venue_id, code)
);

create table gates (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  venue_id      uuid not null references venues(id),
  code          text not null,                        -- 'P4'
  name          text not null,
  directions    text,                                 -- 0-200 chars, how to reach the gate; fan app only, never in the manifest
  latitude      numeric(8,6) check (latitude between -90 and 90),     -- WGS 84, for the "Ouvrir dans Plans" link
  longitude     numeric(9,6) check (longitude between -180 and 180),
  constraint gates_location check ((latitude is null) = (longitude is null)),
  unique (venue_id, code)
);

create table gate_zones (
  organizer_id  uuid not null references organizers(id),
  gate_id       uuid not null references gates(id),
  zone_id       smallint not null references zones(id),
  primary key (gate_id, zone_id)
);

create table event_series (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  name          text not null,                        -- 'Saison 2026-27'
  starts_on     date not null,
  ends_on       date not null
);

create type event_type   as enum ('FOOTBALL_MATCH','CONCERT','FESTIVAL_DAY','CONFERENCE','OTHER');
create type event_status as enum ('DRAFT','ON_SALE','GATES_OPEN','CLOSED');
create type reentry_policy as enum ('NONE','ONE_EXIT');

create table events (
  id                integer generated always as identity primary key,  -- 4-byte event_id travels in the QR
  organizer_id      uuid not null references organizers(id),
  venue_id          uuid not null references venues(id),
  series_id         uuid references event_series(id),
  event_type        event_type not null default 'OTHER',
  title             text not null,
  starts_at         timestamptz not null,             -- T0
  doors_open_at     timestamptz,
  status            event_status not null default 'DRAFT',
  event_key_enc     bytea not null,                   -- K_e, 32 bytes, encrypted with the master key (KMS)
  refund_cutoff_at  timestamptz,                      -- default T0 - 60 min, set on publish
  reentry_policy    reentry_policy not null default 'NONE',
  per_account_limit smallint not null default 4,
  sale_starts_at    timestamptz,                      -- null = on sale from publish; must be < starts_at - 60 min (orders accepted while ON_SALE and sale_starts_at <= now < refund_cutoff_at)
  metadata          jsonb not null default '{}'::jsonb, -- keys per event_type: docs/04-api.md §Event metadata
  created_at        timestamptz not null default now()
);
create index on events (organizer_id, starts_at);

create table price_categories (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  event_id      integer not null references events(id),
  zone_id       smallint not null references zones(id),   -- must belong to the event's venue (checked in the service)
  name          text not null,                        -- 'Plein tarif', 'Abonné'
  price_mad     bigint not null check (price_mad >= 0),  -- centimes
  quota         integer not null check (quota >= 0),
  sold          integer not null default 0 check (sold >= 0 and sold <= quota),
                -- held (RESERVED, AWAITING_CASH) + PAID; incremented atomically on reserve,
                -- decremented when an order expires or is cancelled, and when a ticket is refunded (one place)
  unique (event_id, zone_id, name)
);

-- ---------- sales ----------
create type sales_channel as enum ('APP','WEB','POS');
create type order_status  as enum ('RESERVED','AWAITING_CASH','PAID','EXPIRED','CANCELLED','REFUNDED');
create type payment_method as enum ('CARD','CASH_AGENCY','WALLET','POS_CASH','FREE');

create table orders (
  id              uuid primary key default gen_random_uuid(),
  organizer_id    uuid not null references organizers(id),
  event_id        integer not null references events(id),
  user_id         uuid references users(id),
  channel         sales_channel not null,
  status          order_status not null default 'RESERVED',
  total_mad       bigint not null check (total_mad >= 0),
  payment_method  payment_method,
  payment_ref     text,   -- on PAID: the succeeding payment's provider_ref; for a cash code, the code
  reserved_until  timestamptz not null,
  paid_at         timestamptz,
  created_at      timestamptz not null default now(),
  group_order_id  uuid references orders(id)   -- split pay: set on a member order, = the initiator's order (docs/04-api.md §Split pay)
);
-- AWAITING_CASH: a cash code was issued; reserved_until = least(issue + 24 h, events.refund_cutoff_at).
-- POS sale: channel POS, user_id null, created PAID. Ticket refunds leave the order PAID
-- (order REFUNDED = whole-order refund, Lot 5).
create index on orders (event_id, status);
create index on orders (user_id, created_at desc);
create index on orders (group_order_id) where group_order_id is not null;

create table order_items (
  id                uuid primary key default gen_random_uuid(),
  organizer_id      uuid not null references organizers(id),
  order_id          uuid not null references orders(id),
  price_category_id uuid not null references price_categories(id),
  qty               smallint not null check (qty > 0),
  unit_price_mad    bigint not null check (unit_price_mad >= 0),  -- snapshot at reservation
  holders           jsonb not null default '[]'::jsonb,            -- [{"name": "Yazid Aqel", "user_id": "<uuid>"}], one per place; no phone stored
  constraint order_items_holders_len check (jsonb_array_length(holders) = qty) not valid,  -- Lot 0 rows keep []
  unique (order_id, price_category_id)
);

create type ticket_status as enum ('VALID','CANCELLED','REFUNDED','BLOCKED');

create table tickets (
  id                uuid primary key default gen_random_uuid(),   -- 16 bytes in the QR
  organizer_id      uuid not null references organizers(id),
  order_id          uuid not null references orders(id),
  event_id          integer not null references events(id),
  zone_id           smallint not null references zones(id),
  price_category_id uuid not null references price_categories(id),
  holder_user_id    uuid references users(id),
  holder_initials   text,                              -- 'Y. A.' — derived from holder_name at issue; never the full name in the manifest
  holder_name       text,                              -- full name as entered (docs/04-api.md §Holder names); never in a QR or manifest
  seat_label        text,
  status            ticket_status not null default 'VALID',
  issued_at         timestamptz not null default now()
);
create index on tickets (event_id, status);
create index on tickets (holder_user_id);

create table ticket_transfers (                       -- transfer or re-issue: the old ticket goes CANCELLED, a new one is issued
  id              uuid primary key default gen_random_uuid(),   -- (new ticket_id, so a new K_t; the old QR dies with the next manifest)
  organizer_id    uuid not null references organizers(id),
  ticket_id       uuid not null unique references tickets(id),  -- the ticket cancelled
  new_ticket_id   uuid not null unique references tickets(id),  -- same order, event, zone and price category
  from_user_id    uuid not null references users(id),
  to_user_id      uuid not null references users(id),           -- = from_user_id for a re-issue (lost phone)
  transferred_at  timestamptz not null default now()
);
create index on ticket_transfers (from_user_id, transferred_at desc);

create type pass_status as enum ('ACTIVE','SUSPENDED','CANCELLED');

create table passes (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  series_id     uuid not null references event_series(id),
  user_id       uuid not null references users(id),
  zone_id       smallint not null references zones(id),
  status        pass_status not null default 'ACTIVE',
  created_at    timestamptz not null default now()
);
-- a pass materialises as one tickets row per event in the series (order channel APP, method FREE)

-- ---------- point of sale ----------
create table pos_sessions (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  staff_id      uuid not null references staff(id),      -- the cashier (CASHIER, OPS or ADMIN)
  label         text not null,                          -- 'Guichet Nord', 1-40 chars
  opened_at     timestamptz not null default now(),
  closed_at     timestamptz,
  expected_mad  bigint,                                 -- Σ SUCCEEDED payments of the session, frozen at close (centimes)
  declared_mad  bigint check (declared_mad >= 0),       -- cash counted by the cashier at close (centimes)
  constraint pos_sessions_close check ((closed_at is null) = (expected_mad is null)
                                       and (closed_at is null) = (declared_mad is null))
);
create unique index on pos_sessions (organizer_id, staff_id) where closed_at is null;   -- one open till per cashier

-- ---------- payments ----------
create type payment_status as enum ('PENDING','SUCCEEDED','FAILED');

create table payments (
  id              uuid primary key default gen_random_uuid(),   -- sent to the gateway as its order reference
  organizer_id    uuid not null references organizers(id),
  order_id        uuid not null references orders(id),
  method          payment_method not null,
  provider        text not null,        -- CARD/WALLET: 'FAKE' (simulated, non-prod), 'PAYZONE'. POS_CASH: 'POS'.
                                        -- CASH_AGENCY: 'CASH' while PENDING, then the collector: 'POS' (club till),
                                        -- 'FAKE_CASH' (simulated network) or the network's name.
  amount_mad      bigint not null check (amount_mad >= 0),
  status          payment_status not null default 'PENDING',
  provider_ref    text,                 -- gateway or network transaction id from the callback; null for till payments
  pay_code        text unique,          -- CASH_AGENCY: 6 Crockford base32 symbols (docs/04-api.md §Cash codes), never reused
  pos_session_id  uuid references pos_sessions(id),   -- cash taken at a club till (POS sale or code collected there)
  redirected_at   timestamptz,          -- CARD/WALLET: hosted page opened; the expiry waits only for these (20 min)
  callback        jsonb,                -- last verified callback, card fields stripped
  created_at      timestamptz not null default now(),
  completed_at    timestamptz,
  return_channel  sales_channel check (return_channel in ('APP','WEB')),  -- CARD/WALLET: the client that started the attempt; /return lands there (null = orders.channel)
  constraint payments_pay_code check ((method = 'CASH_AGENCY') = (pay_code is not null))
);
create index on payments (order_id);
create unique index on payments (provider, provider_ref) where provider_ref is not null;
create index on payments (organizer_id, completed_at) where status = 'SUCCEEDED';   -- cash report
create index on payments (pos_session_id) where pos_session_id is not null;

-- ---------- refunds ----------
create type refund_status as enum ('REQUIRED','DONE');

create table refunds (                                 -- money owed back for a refunded ticket; paid back by hand
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  event_id      integer not null references events(id),
  ticket_id     uuid not null unique references tickets(id),
  order_id      uuid not null references orders(id),
  payment_id    uuid references payments(id),           -- the order's succeeding payment (its method says how to pay back)
  amount_mad    bigint not null check (amount_mad >= 0),  -- the item's unit_price_mad snapshot
  reason        text not null,                          -- 1-200 chars
  status        refund_status not null default 'REQUIRED',
  requested_by  uuid not null references staff(id),
  requested_at  timestamptz not null default now(),
  done_by       uuid references staff(id),
  done_at       timestamptz,
  reference     text,                                   -- how it was paid back: transfer, gateway refund id, receipt no
  constraint refunds_done check ((status = 'DONE') = (done_at is not null and done_by is not null and reference is not null))
);
create index on refunds (organizer_id, status, requested_at);

-- ---------- fans ----------
create table memberships (                            -- a fan who joined an organizer's club (free, Lot 4); loyalty is computed on read
  id                  uuid primary key default gen_random_uuid(),
  organizer_id        uuid not null references organizers(id),
  user_id             uuid not null references users(id),
  number              integer not null check (number > 0),   -- member number per organizer, from 1, never reused
  joined_at           timestamptz not null default now(),
  left_at             timestamptz,                           -- left the club; a rejoin clears it and keeps the number and joined_at

create extension if not exists pgcrypto;

-- Tenant rule: every table carries organizer_id, except platform identity tables
-- organizers, users, otp_challenges, fan_sessions, push_tokens (one fan account and one fan app across organizers).
-- audit_log.organizer_id is nullable for SYSTEM actions.
-- Every query on a tenant table filters by organizer_id (no composite FKs: app scoping
-- is needed anyway to return 404 on foreign ids; tested per endpoint).

-- ---------- tenancy ----------
create type organizer_kind as enum ('SPORTS_CLUB','PROMOTER','VENUE','OTHER');

create table organizers (
  id            uuid primary key default gen_random_uuid(),
  name          text not null,
  kind          organizer_kind not null default 'OTHER',
  settings      jsonb not null default '{}'::jsonb,
  created_at    timestamptz not null default now(),
  slug          text unique                           -- public handle (jomhor.ma/{slug}); null = unlisted: not in /fan/organizers nor in "Tout"
                constraint organizers_slug check (
                  slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(slug) between 2 and 40
                  and slug not in ('all', 'api', 'apple-icon', 'ar', 'club', 'clubs', 'en', 'events', 'favicon', 'fr',
                                   'help', 'icon', 'legal', 'login', 'logout', 'manifest', 'me', 'mine',
                                   'opengraph-image', 'orders', 'robots', 'sitemap', 'twitter-image'))
                                                    -- reserved: web shop top-level paths, ?club= values, locale prefixes
);
-- organizers.settings shape: {"crest_url": "https://assets.jomhor.ma/crests/atlas-fc.svg"}
--   the club crest: content only (design/BRAND.md, not white-label). Returned to fans only under the configured crest
--   base URL (docs/04-api.md §Club directory), else null. Set by ops until a back-office editor exists.
--   A Lot 0 "theme" object, if present, is never read by the fan app, the web shop or the scanner.
--   "cash_points": [{"name": "Guichet Stade de l'Atlas", "address": "Porte 1", "hours": "Lun–Sam 10:00–19:00"}]
--   where fans pay a cash code in person; shown on the cash order page. Set by ops until a back-office editor exists.
--   "loyalty": {"tiers": [{"code": "T1", "name": {"fr": "Membre", "ar": "منخرط", "en": "Member"}, "min_events": 0},
--                         {"code": "T2", "name": {"fr": "Fidèle", "ar": "وفي", "en": "Regular"}, "min_events": 3},
--                         {"code": "T3", "name": {"fr": "Pilier", "ar": "ركيزة", "en": "Stalwart"}, "min_events": 10}]}
--   tiers by min_events ascending, the first at 0; absent or malformed = these defaults; a missing locale falls back to "fr".
--   "finance": {"legal_name": "Atlas FC SA", "address": "Stade de l'Atlas, Casablanca", "ice": "001234567000089",
--               "if": "12345678", "rc": "Casablanca 123456", "rib": "011780000012345678901234",
--               "fee_rate_bp": 500, "start_on": "2026-12-01"}
--   Jomhor's fee contract and the organizer's legal and bank details (docs/04-api.md §Finance). Set by Jomhor ops from
--   the signed contract and a RIB certificate; never writable through /org. ice 15 digits, rib 24 digits,
--   fee_rate_bp 0–10 000. Absent: no settlement statements; malformed: none either, with a WARN.

create table users (
  id            uuid primary key default gen_random_uuid(),
  phone_e164    text not null unique,
  display_name  text,
  locale        text not null default 'fr',
  created_at    timestamptz not null default now(),
  verified_at   timestamptz   -- first successful fan OTP login (POST /fan/auth/verify); null = never logged in (e.g. a holder
                              -- typed by a buyer). Account age for on-sale eligibility (docs/04-api.md §Waiting room)
);

create type staff_role as enum ('ADMIN','OPS','GATE','SUPERVISOR','FINANCE','CASHIER');
-- CASHIER: back-office OTP login (staff.user_id set), point of sale only (docs/04-api.md §Point of sale). No PIN.

create table staff (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  user_id       uuid references users(id),            -- back-office staff log in by phone OTP; null = PIN-only gate staff
  name          text not null,
  role          staff_role not null,
  pin_hash      text,   -- scanner PIN verifier 'pbkdf2-sha256$10000$<salt>$<hash>' (docs/04-api.md §Gate PINs).
                        -- GATE/SUPERVISOR rows only; the 4-digit PIN is generated by the server and shown once.
                        -- Shipped to the organizer's scanners: a UI lock, brute-forceable offline by design.
  active        boolean not null default true,
  created_at    timestamptz not null default now(),
  unique (organizer_id, user_id)
);

create table otp_challenges (
  id            uuid primary key default gen_random_uuid(),
  phone_e164    text not null,
  audience      text not null default 'fan' check (audience in ('fan','org')),  -- a code verifies only on its own audience
  ip            inet,                                 -- requester (trusted-proxy resolved), for the per-IP throttle
  code_hash     text not null,                        -- HMAC-SHA256(server secret, code); the code is never stored
  attempts      smallint not null default 0 check (attempts <= 5),
  expires_at    timestamptz not null,                 -- created_at + 5 min
  consumed_at   timestamptz,
  created_at    timestamptz not null default now()
);
create index on otp_challenges (phone_e164, audience, created_at desc);
  -- per phone+audience: 3 sends / 10 min, 10 sends / 24 h; sum(attempts) of failed codes >= 15 in 24 h -> locked
create index on otp_challenges (ip, created_at desc);   -- per IP: docs/04-api.md §Fan auth

create table fan_sessions (
  id            uuid primary key default gen_random_uuid(),   -- JWT `sid`
  user_id       uuid not null references users(id),
  created_at    timestamptz not null default now(),
  expires_at    timestamptz not null,                 -- = JWT exp (30 d)
  revoked_at    timestamptz
);
create index on fan_sessions (user_id) where revoked_at is null;


-- ---------- catalog ----------
create table venues (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  name          text not null,
  city          text,
  capacity      integer not null check (capacity > 0),
  timezone      text not null default 'Africa/Casablanca'  -- IANA zone; every wall time for this venue's events
);

create table zones (
  id            smallserial primary key,              -- 2-byte zone_id in the QR; global sequence, ceiling 32,767 zones platform-wide
  organizer_id  uuid not null references organizers(id),
  venue_id      uuid not null references venues(id),
  code          text not null,                        -- 'NORD', 'EST'
  name          text not null,
  capacity      integer not null check (capacity >= 0),
  seated        boolean not null default false,
  unique (venue_id, code)
);

create table gates (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  venue_id      uuid not null references venues(id),
  code          text not null,                        -- 'P4'
  name          text not null,
  directions    text,                                 -- 0-200 chars, how to reach the gate; fan app only, never in the manifest
  latitude      numeric(8,6) check (latitude between -90 and 90),     -- WGS 84, for the "Ouvrir dans Plans" link
  longitude     numeric(9,6) check (longitude between -180 and 180),
  constraint gates_location check ((latitude is null) = (longitude is null)),
  unique (venue_id, code)
);

create table gate_zones (
  organizer_id  uuid not null references organizers(id),
  gate_id       uuid not null references gates(id),
  zone_id       smallint not null references zones(id),
  primary key (gate_id, zone_id)
);

create table event_series (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  name          text not null,                        -- 'Saison 2026-27'
  starts_on     date not null,
  ends_on       date not null
);

create type event_type   as enum ('FOOTBALL_MATCH','CONCERT','FESTIVAL_DAY','CONFERENCE','OTHER');
create type event_status as enum ('DRAFT','ON_SALE','GATES_OPEN','CLOSED');
create type reentry_policy as enum ('NONE','ONE_EXIT');

create table events (
  id                integer generated always as identity primary key,  -- 4-byte event_id travels in the QR
  organizer_id      uuid not null references organizers(id),
  venue_id          uuid not null references venues(id),
  series_id         uuid references event_series(id),
  event_type        event_type not null default 'OTHER',
  title             text not null,
  starts_at         timestamptz not null,             -- T0
  doors_open_at     timestamptz,
  status            event_status not null default 'DRAFT',
  event_key_enc     bytea not null,                   -- K_e, 32 bytes, encrypted with the master key (KMS)
  refund_cutoff_at  timestamptz,                      -- default T0 - 60 min, set on publish
  reentry_policy    reentry_policy not null default 'NONE',
  per_account_limit smallint not null default 4,
  sale_starts_at    timestamptz,                      -- null = on sale from publish; must be < starts_at - 60 min (orders accepted while ON_SALE and sale_starts_at <= now < refund_cutoff_at)
  metadata          jsonb not null default '{}'::jsonb, -- keys per event_type: docs/04-api.md §Event metadata
  created_at        timestamptz not null default now()
);
create index on events (organizer_id, starts_at);

create type price_audience as enum ('ALL','MEMBERS','PASS','INVITE');

create table price_categories (
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  event_id      integer not null references events(id),
  zone_id       smallint not null references zones(id),   -- must belong to the event's venue (checked in the service)
  name          text not null,                        -- 'Plein tarif', 'Abonné'
  price_mad     bigint not null check (price_mad >= 0),  -- centimes
  quota         integer not null check (quota >= 0),
  sold          integer not null default 0 check (sold >= 0 and sold <= quota),
                -- held (RESERVED, AWAITING_CASH) + PAID; incremented atomically on reserve,
                -- decremented when an order expires or is cancelled, and when a ticket is refunded (one place)
  audience      price_audience not null default 'ALL',  -- MEMBERS: each place held by a live member of the organizer who joined
                                                         -- before events.sale_starts_at (docs/04-api.md POST /fan/orders)
                                                         -- PASS: places for season-pass holders of the event's series (docs/04-api.md §Passes);
                                                         -- issued by the pass job only, never sold to fans or at a till; price_mad = 0
                                                         -- INVITE: places for invitations and accreditations (docs/04-api.md §Invitations);
                                                         -- issued from the back-office only, never sold to fans or at a till; price_mad = 0.
                                                         -- The category name is the kind ('Presse', 'Invités').
  unique (event_id, zone_id, name),
  constraint price_categories_free check (audience not in ('PASS','INVITE') or price_mad = 0)
);

-- ---------- sales ----------
create type sales_channel as enum ('APP','WEB','POS');
create type order_status  as enum ('RESERVED','AWAITING_CASH','PAID','EXPIRED','CANCELLED','REFUNDED');
create type payment_method as enum ('CARD','CASH_AGENCY','WALLET','POS_CASH','FREE');

-- ---------- sales: products (Lot 5 step 3) ----------
create type product_kind as enum ('PASS','MEMBERSHIP');

create table products (                               -- what an order sells besides event places (docs/04-api.md §Products)
  id              uuid primary key default gen_random_uuid(),
  organizer_id    uuid not null references organizers(id),
  kind            product_kind not null,
  name            text not null check (char_length(name) between 1 and 60),   -- organizer content, shown as typed
  price_mad       bigint not null check (price_mad > 0),                      -- centimes; snapshot in order_items
  on_sale         boolean not null default false,
  sales_close_at  timestamptz not null,                 -- no product order at or after; caps a cash code's hold
  quota           integer check (quota >= 0),           -- PASS: passes on sale; null for MEMBERSHIP (no cap)
  sold            integer not null default 0 check (sold >= 0 and (quota is null or sold <= quota)),
                  -- PASS: passes PENDING, ACTIVE or SUSPENDED; 0 for MEMBERSHIP
  series_id       uuid references event_series(id),     -- PASS: the events it covers
  zone_id         smallint references zones(id),        -- PASS: the zone its tickets admit to; events at that zone's venue only
  valid_until     timestamptz,                          -- MEMBERSHIP: the memberships.paid_until it grants
  max_installments smallint not null default 1 check (max_installments between 1 and 10),
                  -- PASS: the most payments a fan may choose (1 = in full only); docs/04-api.md §Passes Installments
  created_at      timestamptz not null default now(),
  constraint products_kind check (
    (kind = 'PASS') = (series_id is not null and zone_id is not null and quota is not null)
    and (kind = 'MEMBERSHIP') = (valid_until is not null)),
  constraint products_installments check (kind = 'PASS' or max_installments = 1)
);
create index on products (organizer_id, kind);

-- ---------- sales: passes (Lot 5 step 3) ----------
create type pass_status as enum ('PENDING','ACTIVE','SUSPENDED','CANCELLED');

create table passes (                                 -- a season pass (docs/04-api.md §Passes): one ticket per event of its series
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  product_id    uuid not null references products(id),     -- kind PASS (zone, price)
  series_id     uuid not null references event_series(id), -- = the product's; one live pass per account per series
  user_id       uuid not null references users(id),        -- buyer and holder
  holder_name   text not null,                              -- §Holder names; copied to its tickets; never in a QR or manifest
  status        pass_status not null default 'PENDING',     -- PENDING until its purchase order is PAID; CANCELLED if that expires
  suspended_at  timestamptz,                                -- an installment overdue past passes.grace; null unless SUSPENDED
  created_at    timestamptz not null default now(),
  constraint passes_suspended check ((status = 'SUSPENDED') = (suspended_at is not null))
);
create unique index on passes (series_id, user_id) where status <> 'CANCELLED';
-- a pass's ticket for an event comes from an order with pass_id and event_id set (channel APP, method FREE,
-- one PASS-category place); see docs/04-api.md §Passes. A SUSPENDED pass's tickets read BLOCKED without
-- any write to tickets rows (docs/04-api.md §Passes Effective status)

-- ---------- sales: promo codes (Lot 5 step 4) ----------
create type promo_kind as enum ('PERCENT','AMOUNT');

create table promo_codes (                            -- docs/04-api.md §Promo codes
  id                uuid primary key default gen_random_uuid(),
  organizer_id      uuid not null references organizers(id),
  event_id          integer not null references events(id),
  price_category_id uuid references price_categories(id),   -- null = every ALL/MEMBERS category of the event
  code              text not null check (code ~ '^[A-Z0-9]{4,20}$'),   -- uppercase; fans type any case
  kind              promo_kind not null,
  percent           smallint check (percent between 1 and 99),   -- PERCENT: floor(eligible × percent / 100)
  amount_mad        bigint check (amount_mad > 0),               -- AMOUNT: centimes off, once per order
  max_uses          integer check (max_uses > 0),                -- orders RESERVED/AWAITING_CASH/PAID with it; null = no cap
  per_account_max   smallint not null default 1 check (per_account_max between 1 and 100),
  active            boolean not null default true,
  created_at        timestamptz not null default now(),
  unique (event_id, code),
  constraint promo_codes_kind check ((kind = 'PERCENT') = (percent is not null)
                                     and (kind = 'AMOUNT') = (amount_mad is not null))
);

create table orders (
  id              uuid primary key default gen_random_uuid(),
  organizer_id    uuid not null references organizers(id),
  event_id        integer references events(id),   -- null = a product order (pass purchase or installment, membership)
  pass_id         uuid references passes(id),      -- event_id null: the pass's purchase or installment order;
                                                   -- event_id set: the pass's ticket order for that event (PAID, FREE, total 0)
  user_id         uuid references users(id),
  channel         sales_channel not null,
  status          order_status not null default 'RESERVED',
  total_mad       bigint not null check (total_mad >= 0),
  payment_method  payment_method,
  payment_ref     text,   -- on PAID: the succeeding payment's provider_ref; for a cash code, the code
  reserved_until  timestamptz not null,
  paid_at         timestamptz,
  created_at      timestamptz not null default now(),
  group_order_id  uuid references orders(id),  -- split pay: set on a member order, = the initiator's order (docs/04-api.md §Split pay)
  invited_by      uuid references staff(id),   -- an invitation (docs/04-api.md §Invitations): the staff who issued it;
                                               -- PAID, channel POS, user_id null, payment_method FREE, total 0
  promo_code_id   uuid references promo_codes(id),   -- the code this (buyer's) order used
  discount_mad    bigint not null default 0 check (discount_mad >= 0),
                  -- centimes; total_mad = Σ qty × unit_price_mad − discount_mad (unit_price_mad stays the list price)
  constraint orders_product check (event_id is not null or (channel in ('APP','WEB') and group_order_id is null)),
  constraint orders_invited check (invited_by is null
                                   or (event_id is not null and channel = 'POS' and user_id is null and pass_id is null)),
  constraint orders_promo check (promo_code_id is not null or discount_mad = 0)
);
-- AWAITING_CASH: a cash code was issued; reserved_until = least(issue + 24 h, events.refund_cutoff_at).
-- POS sale: channel POS, user_id null, created PAID. Ticket refunds leave the order PAID
-- (order REFUNDED = whole-order refund, Lot 5).
create index on orders (event_id, status);
create index on orders (user_id, created_at desc);
create index on orders (group_order_id) where group_order_id is not null;
create unique index on orders (pass_id, event_id) where pass_id is not null and event_id is not null;  -- one ticket order per pass per event
create index on orders (pass_id) where pass_id is not null;
create index on orders (event_id, created_at desc) where invited_by is not null;
create index on orders (promo_code_id, status) where promo_code_id is not null;   -- caps (docs/04-api.md §Promo codes)

create table order_items (
  id                uuid primary key default gen_random_uuid(),
  organizer_id      uuid not null references organizers(id),
  order_id          uuid not null references orders(id),
  price_category_id uuid references price_categories(id),  -- an event place; null on a product item
  product_id        uuid references products(id),          -- a product item (qty 1, one holder)
  qty               smallint not null check (qty > 0),
  unit_price_mad    bigint not null check (unit_price_mad >= 0),  -- snapshot at reservation
  holders           jsonb not null default '[]'::jsonb,            -- [{"name": "Yazid Aqel", "user_id": "<uuid>"}], one per place; no phone stored
  constraint order_items_holders_len check (jsonb_array_length(holders) = qty) not valid,  -- Lot 0 rows keep []
  constraint order_items_subject check ((price_category_id is null) <> (product_id is null)),
  unique (order_id, price_category_id)
);
create index on order_items using gin (holders jsonb_path_ops);  -- holder limit: places one account holds (docs/04-api.md POST /fan/orders)

-- ---------- sales: pass installments (Lot 5 step 3) ----------
create table pass_installments (                      -- a pass's payment schedule (docs/04-api.md §Passes Installments)
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  pass_id       uuid not null references passes(id),
  seq           smallint not null check (seq between 1 and 10),
  amount_mad    bigint not null check (amount_mad > 0),   -- centimes; Σ over the pass = the product price at purchase
  due_at        timestamptz not null,                     -- seq 1: the purchase; seq k: created_at + (k − 1) × passes.installment-interval
  order_id      uuid unique references orders(id),        -- the PAID order that paid it
  paid_at       timestamptz,
  reminded_at   timestamptz,                              -- INSTALLMENT_DUE queued (once)
  unique (pass_id, seq),
  constraint pass_installments_paid check ((order_id is null) = (paid_at is null))
);
create index on pass_installments (due_at) where paid_at is null;

create type ticket_status as enum ('VALID','CANCELLED','REFUNDED','BLOCKED');

create table tickets (
  id                uuid primary key default gen_random_uuid(),   -- 16 bytes in the QR
  organizer_id      uuid not null references organizers(id),
  order_id          uuid not null references orders(id),
  event_id          integer not null references events(id),
  zone_id           smallint not null references zones(id),
  price_category_id uuid not null references price_categories(id),
  holder_user_id    uuid references users(id),
  holder_initials   text,                              -- 'Y. A.' — derived from holder_name at issue; never the full name in the manifest
  holder_name       text,                              -- full name as entered (docs/04-api.md §Holder names); never in a QR or manifest
  seat_label        text,
  status            ticket_status not null default 'VALID',
  issued_at         timestamptz not null default now()
);
create index on tickets (event_id, status);
create index on tickets (holder_user_id);

create table ticket_transfers (                       -- transfer or re-issue: the old ticket goes CANCELLED, a new one is issued
  id              uuid primary key default gen_random_uuid(),   -- (new ticket_id, so a new K_t; the old QR dies with the next manifest)
  organizer_id    uuid not null references organizers(id),
  ticket_id       uuid not null unique references tickets(id),  -- the ticket cancelled
  new_ticket_id   uuid not null unique references tickets(id),  -- same order, event, zone and price category
  from_user_id    uuid not null references users(id),
  to_user_id      uuid not null references users(id),           -- = from_user_id for a re-issue (lost phone)
  transferred_at  timestamptz not null default now()
);
create index on ticket_transfers (from_user_id, transferred_at desc);

-- ---------- sales: waiting rooms (Lot 5) ----------
create type room_status as enum ('SCHEDULED','PRE_QUEUE','OPEN','PAUSED','ENDED');

create table waiting_rooms (                          -- high-demand on-sale (docs/04-api.md §Waiting room); one per phase of an event
  id                      uuid primary key default gen_random_uuid(),
  organizer_id            uuid not null references organizers(id),
  event_id                integer not null references events(id),   -- no longer unique (Lot 5 step 2)
  phase                   smallint not null default 1 check (phase between 1 and 5),
                          -- sale phases in order; a phase ends when the next one's opens_at passes
  label                   text check (char_length(label) between 1 and 40),  -- shown to fans as typed ('Prévente membres'); null = none
  starts_at               timestamptz,   -- this phase's sale start (its draw); null for phase 1 = events.sale_starts_at
  status                  room_status not null default 'SCHEDULED',
  pre_queue_min           smallint not null default 30 check (pre_queue_min between 0 and 1440),
                          -- joins open at the phase's sale start - pre_queue_min; joins before the sale start are drawn at random
  admission_rate_per_min  integer not null default 500 check (admission_rate_per_min between 1 and 6000),
  min_account_age_days    smallint check (min_account_age_days between 1 and 365),  -- eligibility, each null = not required:
  member_joined_before    timestamptz,                                              --   verified_at <= sale_starts_at - n days;
  min_events_attended     smallint check (min_events_attended between 1 and 50),    --   member since before; events attended
  joined_count            integer not null default 0,     -- written by the room tick
  ranked_count            integer not null default 0,     -- entries with a rank: ranks are 1..ranked_count
  admitted_through        integer not null default 0,     -- ranks <= this are admitted
  measured_rate_per_min   integer not null default 0,     -- admitted over the last full minute
  rate_mark_at            timestamptz,
  rate_mark_through       integer not null default 0,
  sold_out                boolean not null default false, -- every category remaining = 0 at the last tick
  last_tick_at            timestamptz,
  drawn_at                timestamptz,
  created_at              timestamptz not null default now(),
  unique (event_id, phase),
  constraint waiting_rooms_admitted check (admitted_through <= ranked_count),
  constraint waiting_rooms_starts check ((phase = 1) = (starts_at is null))
);
create index on waiting_rooms (status) where status <> 'ENDED';

create table queue_entries (                          -- one per account per room; sub of the queue token
  id            uuid primary key default gen_random_uuid(),
  organizer_id  uuid not null references organizers(id),
  room_id       uuid not null references waiting_rooms(id),
  user_id       uuid not null references users(id),
  device_hash   bytea not null check (length(device_hash) = 32),  -- HMAC-SHA256(rooms secret, device_id); never the raw id
  ip_hash       bytea not null check (length(ip_hash) = 32),      -- HMAC-SHA256(rooms secret, "ip|" + client IP via trusted proxies); never the raw IP
  draw_key      bigint not null,                      -- 8 CSPRNG bytes drawn at join; orders the draw; never returned
  joined_at     timestamptz not null default now(),   -- a rejoin after an expired turn resets it (back of the queue)
  rank          integer check (rank > 0),             -- dense per room, set by the room tick; null until ranked
  admitted_at   timestamptz,                          -- first poll that saw rank <= admitted_through; the turn ends 10 min later
  unique (room_id, user_id),
  unique (room_id, rank)
);
create index on queue_entries (room_id, joined_at) where rank is null;
create index on queue_entries (room_id, device_hash);
create index on queue_entries (room_id, ip_hash, joined_at);   -- per-IP join limit (docs/04-api.md §Waiting room)
-- Rows are deleted 30 days after the event's starts_at (rooms.retention).


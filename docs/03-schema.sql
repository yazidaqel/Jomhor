-- ---------- audit ----------
-- Owned by the shared kernel (backend `ma.jomhor.common.AuditLog`): every module writes through it.
create table audit_log (
  id            bigserial primary key,
  organizer_id  uuid,
  actor_type    text not null,                        -- STAFF, USER, SYSTEM, DEVICE
  actor_id      uuid,
  action        text not null,                        -- 'ticket.block', 'event.publish', ...
  target        text,
  payload       jsonb,
  at            timestamptz not null default now()
);
create index on audit_log (organizer_id, action, at);
